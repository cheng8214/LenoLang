#include "semantic_internal.h"

// ============================================================================
// semantic_visit.c - 语义分析 AST 访问模块入口
// ============================================================================
// 
// 本文件是语义分析阶段 AST 访问的入口模块。
// 实际实现已拆分到以下文件：
//
// - semantic_visit_method.c : struct 方法字段访问转换
//   - transform_method_body() : 将方法体中对字段名和方法名的访问转换为 self.字段名 / StructName::method(self, args)
//
// - semantic_visit_ast.c : AST 访问者模式实现
//   - visit() : 访问者模式主函数，处理所有 AST 节点类型
//   - visit_list() : 访问 AST 列表
//
// - semantic_visit_func.c : 函数处理
//   - visit_func() : 处理函数定义，包括参数、作用域、函数体分析
//
// ============================================================================
